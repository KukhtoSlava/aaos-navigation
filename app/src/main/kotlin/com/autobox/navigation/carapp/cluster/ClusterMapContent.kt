/** Low-poly car in app/src/main/assets, generated by tools/make_car_model.py. */
private const val CAR_MODEL_ASSET = "autobox_car.glb"

// The cluster is read at a glance: the car is drawn larger than the SDK's default marker.
private const val CAR_MODEL_MAGNIFICATION = 1.8

// A driver's view rather than a map: close in and steeply tilted, so the streets and
// buildings ahead rise towards the horizon behind the car.
private const val CLUSTER_ZOOM = 17.5
private const val CLUSTER_TILT = 62.0

private val clusterCameraConfig = FollowCameraOperatorConfig(
    defaultZoom = CLUSTER_ZOOM,
    defaultTilt = CLUSTER_TILT,
)

/**
 * Map for the AAOS instrument cluster, drawn under the cluster's gauges.
 *
 * Always dark and always following the car. During guidance the route is highlighted, with
 * TomTom's instruction arrows at the maneuvers, and a card shows the next maneuver. The map is
 * not interactive: the cluster has no touch input.
 *
 * @param safeArea The part of the surface not covered by the cluster UI. The camera keeps the
 *   car in it and the maneuver card is placed at its top.
 * @param onMapReady Called once the map is up on the surface.
 */
@Composable
fun ClusterMapContent(safeArea: PaddingValues, onMapReady: () -> Unit = {}) {
    val mapDisplayInfrastructure = remember {
        MapDisplayInfrastructure(sdkContext = TomTomSdk.sdkContext) {
            locationInfrastructure = MapLocationInfrastructure {
                locationProvider = VehicleLocation.provider
            }
        }
    }
    val navigationInfrastructure = remember {
        NavigationVisualizationInfrastructure(
            routingVisualizationDataProvider = flowOf(
                RoutingVisualizationDataProvider(
                    routes = ClusterData.clusterRoutes,
                    selectedRouteId = ClusterData.clusterSelectedRoute.map { it?.id },
                ),
            ),
            navigationVisualizationDataProvider = flowOf(
                NavigationVisualizationDataProvider(tomtomNavigation = TomTomSdk.navigation),
            ),
        )
    }

    val mapViewState = rememberMapViewState(
        initialCameraOptions = InitialCameraOptions.LocationBased(
            position = VehicleLocation.provider.lastKnownLocation?.position ?: VehicleLocation.SIMULATION_START,
            zoom = CLUSTER_ZOOM,
            tilt = CLUSTER_TILT,
        ),
    ) {
        styleState.styleMode = StyleMode.DARK
    }

    LaunchedEffect(safeArea) {
        mapViewState.safeArea = safeArea
    }

    val isGuiding by ClusterData.isActiveGuidance.collectAsStateWithLifecycle()
    LaunchedEffect(isGuiding) {
        mapViewState.cameraState.trackingMode = if (isGuiding) {
            CameraTrackingMode.FollowRouteDirection(clusterCameraConfig)
        } else {
            CameraTrackingMode.FollowDirection(clusterCameraConfig)
        }
    }

    val maneuver by ClusterData.nextManeuver.collectAsStateWithLifecycle()
    val context = LocalContext.current
    val carModelUri = remember { carModelFile(context) }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(colorResource(R.color.cluster_map_background)),
    ) {
        TomTomMap(
            infrastructure = mapDisplayInfrastructure,
            state = mapViewState,
            onMapReady = onMapReady,
        ) {
            CurrentLocationMarker(
                properties = CurrentLocationMarkerProperties {
                    type = LocationMarkerOptions.Type.Custom
                    customModel = carModelUri
                    markerMagnification = CAR_MODEL_MAGNIFICATION
                },
            )

            NavigationVisualization(infrastructure = navigationInfrastructure)
        }

        maneuver?.let {
            ManeuverCard(
                maneuver = it,
                modifier = Modifier
                    .padding(safeArea)
                    .align(Alignment.TopCenter),
            )
        }
    }
}

// The standard renderer reads custom models from files only: asset:// URIs fail to load
// ("Required indices are missing"), even for the SDK's own chevron.glb.
private fun carModelFile(context: Context): Uri {
    val file = context.filesDir.resolve(CAR_MODEL_ASSET)
    context.assets.open(CAR_MODEL_ASSET).use { input ->
        file.outputStream().use { input.copyTo(it) }
    }
    return Uri.fromFile(file)
}
